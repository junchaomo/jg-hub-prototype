/** CJK 文本用 UCS2 十六进制串，字形走 Adobe-GB1 的 STSong-Light（阅读器可替换同族字体） */
const pdfHex = (s) => `<${Buffer.from(String(s), 'utf16le').swap16().toString('hex').toUpperCase()}>`

function pdf({ title, body }) {
  const lines = [title, '', ...String(body || '').split('\n')]
  const pageLines = []
  let bucket = []
  for (const line of lines) {
    bucket.push(line)
    if (bucket.length >= 34) { pageLines.push(bucket); bucket = [] }
  }
  if (bucket.length) pageLines.push(bucket)

  const objects = []
  const pageCount = pageLines.length
  const kids = []
  const contents = []
  // 1 目录 2 页面树 3 字体 4 CIDFont 5 字体描述 后接每页 content/page
  const fontObjNum = 3
  pageLines.forEach((_, i) => { contents.push(6 + i * 2) })

  objects[1] = `<< /Type /Catalog /Pages 2 0 R >>`
  objects[2] = `<< /Type /Pages /Count ${pageCount} /Kids [${pageLines.map((_, i) => `${7 + i * 2} 0 R`).join(' ')}] >>`
  objects[3] = `<< /Type /Font /Subtype /Type0 /BaseFont /STSong-Light /Encoding /UniGB-UCS2-H /DescendantFonts [4 0 R] >>`
  objects[4] = `<< /Type /Font /Subtype /CIDFontType0 /BaseFont /STSong-Light /CIDSystemInfo << /Registry (Adobe) /Ordering (GB1) /Supplement 4 >> /FontDescriptor 5 0 R /DW 1000 >>`
  objects[5] = `<< /Type /FontDescriptor /FontName /STSong-Light /Flags 6 /FontBBox [-25 -254 1000 880] /ItalicAngle 0 /Ascent 880 /Descent -120 /CapHeight 700 /StemV 93 >>`

  pageLines.forEach((pl, i) => {
    const y0 = 800
    const cmds = ['BT', `/F1 12 Tf`, `14 TL`, `1 0 0 1 60 ${y0} Tm`]
    pl.forEach((line) => {
      cmds.push(`${pdfHex(line)} Tj`)
      cmds.push('T*')
    })
    cmds.push('ET')
    const stream = cmds.join('\n')
    objects[6 + i * 2] = `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`
    objects[7 + i * 2] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${6 + i * 2} 0 R >>`
  })

  let out = '%PDF-1.4\n'
  const offsets = []
  for (let i = 1; i < objects.length; i += 1) {
    if (!objects[i]) continue
    offsets[i] = Buffer.byteLength(out)
    out += `${i} 0 obj\n${objects[i]}\nendobj\n`
  }
  const xrefStart = Buffer.byteLength(out)
  const size = objects.length
  out += `xref\n0 ${size}\n0000000000 65535 f \n`
  for (let i = 1; i < size; i += 1) {
    out += `${String(offsets[i] || 0).padStart(10, '0')} 00000 n \n`
  }
  out += `trailer\n<< /Size ${size} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`
  return Buffer.from(out, 'binary')
}

const FORMATS = {
  pdf: { ext: 'pdf', mime: 'application/pdf', make: pdf },
  docx: { ext: 'docx', mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', make: docx },
  xlsx: { ext: 'xlsx', mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', make: xlsx },
  pptx: { ext: 'pptx', mime: 'application/vnd.openxmlformats-officedocument.presentationml.presentation', make: pptx },
}

export function buildDocument({ format, title, body, table, slides }) {
  const f = FORMATS[format]
  if (!f) throw new Error(`不支持的格式：${format}`)
  return { buffer: f.make({ title, body, table, slides }), ext: f.ext, mime: f.mime }
}

